// 无限创作工作流 v6 — 段弧多场景版
// 核心：规划段弧 → 分多场景写作 → grep 硬查重 → 无重复写入
// 每一段弧包含多个场景，循序渐进推向高潮
// 使用: Workflow({ scriptPath: 'D:/Stories/default/.workflow.v6.js' })
// 默认循环 50 段弧，可传 args: { arcs: N } 自定义

export const meta = {
  name: 'novel-writer-v6',
  description: '规划段弧 → 多场景分步写作 → 逐场景 grep 硬查重写入',
  phases: [
    { title: '规划段弧', detail: '基于当前进度规划一段弧（3~5个场景），含修炼推进和剧情高潮' },
    { title: '分场景写作中', detail: '按计划写每个场景' },
    { title: 'grep 查重中', detail: '逐句 grep 比对全文，发现重复退回重写' },
    { title: '追加写入中', detail: '确认无重复后写入正文末尾' },
  ],
}

const STORY_FILE = 'D:/Stories/default/正文.md'
const OUTLINE_FILE = 'D:/Stories/default/大纲.md'
const LB = '【', RB = '】'

const MAX_ARCS = args?.arcs || 50
let arcCount = 0

while (arcCount < MAX_ARCS) {
  arcCount++
  log(`\n========== 第 ${arcCount}/${MAX_ARCS} 段弧 ==========`)

  // ══════════════════════════════════════════
  // 阶段一：规划段弧
  // ══════════════════════════════════════════
  phase('规划段弧')

  const arc = await agent(
    `你是编剧。你的任务是基于正文当前进度和世界观大纲，规划下一段弧。

## 规则

1. 用 Read 工具完整读取 ${STORY_FILE} 和 ${OUTLINE_FILE}
2. 正文最后一句就是当前的位置，弧只能从这里开始
3. 每段弧包含 **3~5 个场景**，循序渐进，推到一个小高潮
4. 时间线只能向前，不能回溯
5. **每段弧必须出场 20 个以上新人物/新活物**，其中至少 5 个有名字，其余可以是路人/怪物/生物
6. **怪物该出场就出场**——荒原野兽、谷中异虫、变异生物等，根据场景需要自然出现
7. 最终确认：理解当前修炼数值（储量/密度/共鸣/阶位），确保弧的规划不违反修炼规则

## 修炼铁律（严格遵守，违者失败）
**储量不满 → 无法压缩密度 → 无法推共鸣 → 无法突破。** 顺序不可颠倒。
- 空修二阶·触隙：上限 100U。当前 32U，**储量未满之前密度（2）和共鸣（3）不能提升**
- 武道一阶·铁骨：上限 10U、密度 2、共鸣 2。已满，**可通过战斗推共鸣 2->3 后突破二阶·铜皮**
- 空修突破三阶需要：储量 100U + 密度 3 + 共鸣 4

## 输出格式

返回一个场景数组，每个场景包含场景名和一句话内容描述：`,
    {
      label: `规划段弧 #${arcCount}`,
      schema: {
        type: 'object',
        properties: {
          arcTitle: { type: 'string', description: '本段弧的主题' },
          newNamedChars: { type: 'array', items: { type: 'string' }, description: '本段弧新出场的有名字角色（至少5个）' },
          newMonsters: { type: 'array', items: { type: 'string' }, description: '本段弧新出场的怪物/生物种类' },
          scenes: {
            type: 'array',
            items: {
              type: 'object',
              properties: {
                name: { type: 'string', description: '场景名' },
                summary: { type: 'string', description: '一句话说明本场景发生什么' },
                cultivationChange: { type: 'string', description: '修炼数值变化（如果有）' },
              },
              required: ['name', 'summary'],
            },
            description: '3~5 个场景',
          },
        },
        required: ['arcTitle', 'newNamedChars', 'scenes'],
      },
    }
  )

  log(`段弧主题：${arc.arcTitle}（${arc.scenes.length} 个场景）`)

  // ══════════════════════════════════════════
  // 阶段二：逐个场景写作 + 查重 + 写入
  // ══════════════════════════════════════════

  for (let s = 0; s < arc.scenes.length; s++) {
    const scene = arc.scenes[s]
    log(`  → 场景 ${s + 1}/${arc.scenes.length}：${scene.name}`)

    phase('分场景写作中')

    const written = await agent(
      `[强制规则] 你是一个续写型小说作家。你只负责写"下一段发生的事"，绝不重写已经写过的内容。

## 当前段弧背景
段弧主题：${arc.arcTitle}
本场景：${scene.name}
场景概要：${scene.summary}

## 🔴 三条铁律（违反任意一条算失败）

铁律1 — 必须读全文：用 Read 工具完整读取 ${STORY_FILE} 的**全部内容**。
铁律2 — 只续写不重写：读完正文后，找到**最后一句**，你的 output 只能从那里开始向后写。
铁律3 — 输出零重复：你的 content 中如果出现任何一个已经在正文中存在过的字、词、句、场景、对话——算整轮失败。

## ⚠️ 续写规则
- 你读完全文后，**只能从正文最后一句话的结尾处继续往下写**
- 正文中已有的场景、人物、对话全部视为"已经发生过了"，绝对不能再提
- 不可以重新描述已写过的场景样貌、不可以重新介绍人物来历
- 不可以写"第二天""另一天""与此同时"来回到过去
- **时间线只能向前推进**，新的场景必须紧接在正文末尾之后

## 💪 修炼体系规则（最严格限制，违反算失败）
**核心原则：储量不满 → 无法压缩密度 → 无法推共鸣 → 无法突破。** 顺序不可颠倒。

当前数据以正文最新状态为准。注意：
- **空修**：储量未满之前，密度和共鸣不能提升
- **武道**：储量满了之后，可以通过战斗推共鸣，共鸣达标后可突破
- 不涉及突破的场景不要硬写突破

## 📖 书页规则（严格）

**任何境界突破或阶位跃迁后，必须在正文中输出对应纹路的完整书页。** 不输出算失败。

- 空修突破 → **壑纹**书页
- 武修突破 → **骸纹**书页

书页格式（**必须包含以下全部字段，缺一不可**）：

\`\`\`
${LB}对应纹路名称${RB}
  体系：<空/武/...>
  境界：<当前境界·阶段>
  能量类型：<隙能/渊能/...>
  能量储量（Q）：<数值>U
  杂质容量（Q₀）：<数值>
  有效能量（Q - Q₀）：<数值>U
  能量密度（C）：<数值>
  共鸣系数（P）：<数值>
  本源纯率（η）：<数值>
  综合能级（E）：<数值>
  阶位：<几阶>
  能级评价：<10~20字吐槽风格，幽默毒舌>

  已解锁能力：
  · <能力1>：<说明>
  · <能力2>：<说明>

  下一阶位：<名称>
  前置条件：<条件说明>
  突破条件：<条件说明>
  达成后能力：<预览说明>
\`\`\`

- 能级评价**严格限制10~20字**，幽默毒舌风
- 突破后**立即输出**，不能拖到后面补

## 👥 人物与群像规则
- **每个场景都要有新的面孔和活物**——路人、商贩、猎户、怪物、野兽，不能让场景空转
- **本段弧规划了 ${arc.scenes.length > 2 ? '众多新角色出场，包括：' + (arc.newNamedChars || []).join('、') : '新角色出场'}**
- **怪物该出场就出场**——根据场景环境自然引入对应的怪物/生物
- 对话要体现人物性格差异，不能所有人一个口吻
- **放开来写**，大纲是参考不是圣经

## ❤️ 情感深度规则
- 关键节点每个人物必须有符合其性格的情绪反应
- 七情（喜怒哀惧爱恶欲）是底色，体现**高级情绪**：愧疚、嫉妒、怜悯、焦虑、愤懑、眷恋、敬畏、希望、绝望、矛盾、孤寂、感激、戒备、振奋等
- **不要直接说"他很愤怒"**，用行为表现

## ✍️ 写作风格规则
- ❌ 禁止出现章节标识
- ❌ 禁止使用破折号 ——（用逗号句号代替）
- ❌ 禁止在末尾添加总结或伏笔提示
- ✅ 旁白无特殊符号，包含详细场景描写
- ✅ 心理想法用「」括起来
- ✅ 对话用“”括起来
- ✅ 战斗描写：蓄力→释放→反馈
- ✅ 场景包含：时间、光线、声音、气味、空间布局

## ⭐ 最终确认（执行顺序：先做这三步再输出）
1. 用 Read 工具确认正文**当前**最后一句是什么 — 这是你起笔的位置
2. **逐句检查你的 content：如果content中的句子在正文里能找到 → 删掉**
3. 确认 content 中 100% 都是全新的文字

注意：输出纯场景正文，不要加标题、分隔线、章节号。直接接续正文。`,
      {
        label: `场景 ${s + 1}/${arc.scenes.length}`,
        schema: {
          type: 'object',
          properties: {
            content: { type: 'string', description: '场景正文' },
          },
          required: ['content'],
        },
      }
    )

    // ─── grep 硬查重 ───
    phase('grep 查重中')

    const dedupResult = await agent(
      `你是一个严格的查重工具。你的任务是将待写入的内容逐句与现有正文比对，**发现重复就拒绝**。

## 步骤

1. 用 Read 工具读取 ${STORY_FILE} 全文
2. 逐句检查要写入的内容是否在正文中出现过
3. 判断标准：
   - 完整句子匹配 → 重复
   - 关键短语（超过 10 个字）匹配 → 重复
   - 场景描述、对话、心理活动与正文已有内容雷同 → 重复
   - **有一句重复就算整段重复，不能部分写入**
4. 如果不确定，运行 Bash 命令 grep 精确匹配

## 要检查的内容

${written.content}

## 输出格式

{ "passed": true/false, "reason": "如果有重复，说明具体哪几句重复" }`,
      {
        label: `查重 #${arcCount}-${s + 1}`,
        schema: {
          type: 'object',
          properties: {
            passed: { type: 'boolean' },
            reason: { type: 'string', description: '如果 failed，具体哪里重复' },
          },
          required: ['passed', 'reason'],
        },
      }
    )

    if (!dedupResult.passed) {
      log(`  ❌ 查重未通过：${dedupResult.reason}，场景跳过`)
      continue
    }

    // ─── 追加写入 ───
    phase('追加写入中')

    await agent(
      `将以下内容追加到 ${STORY_FILE} 末尾。

规则：
1. 使用 Read 工具读取文件**全文**，确认最后一句
2. 使用 Edit 工具，将最后一行替换为"原最后一行 + \\n\\n + 以下内容"
3. 绝对禁止使用 Write 工具（会覆盖全文件）
4. 绝对禁止修改已有内容

要追加的内容：
"""${written.content}"""`,
      { label: `写入场景 ${s + 1}` }
    )

    log(`  ✅ 场景 ${s + 1} 完成`)
  }

  log(`========== 第 ${arcCount} 段弧完成 ==========\n`)
}

return `完成 ${arcCount} 段弧创作`
